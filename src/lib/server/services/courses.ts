const WEEKDAYS_SHORT = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

/**
 * A course's sessions: upcoming, non-cancelled sessions generated by the
 * course's own templates (`class_template.course_id`). Sessions materialize
 * continuously until `endsOn` — enrollees are auto-booked into each one.
 */
async function courseSessions(orgId: string, c: typeof course.$inferSelect) {
	return db
		.select({
			id: classSession.id,
			capacity: classSession.capacity,
			startsAt: classSession.startsAt
		})
		.from(classSession)
		.innerJoin(classTemplate, eq(classSession.templateId, classTemplate.id))
		.where(
			and(
				eq(classSession.organizationId, orgId),
				eq(classTemplate.courseId, c.id),
				isNull(classSession.cancelledAt),
				gt(classSession.startsAt, new Date())
			)
		)
		.orderBy(asc(classSession.startsAt));
}

/** Staff view: every course with enrollee count, schedule summary, and sessions left. */
export async function listCourses(orgId: string) {
	const rows = await db
		.select({ course, className: classType.name })
		.from(course)
		.innerJoin(classType, eq(course.classTypeId, classType.id))
		.where(eq(course.organizationId, orgId))
		.orderBy(asc(course.startsOn));
	const tpls = rows.length
		? await db
				.select({
					courseId: classTemplate.courseId,
					weekday: classTemplate.weekday,
					startTime: classTemplate.startTime
				})
				.from(classTemplate)
				.where(
					inArray(
						classTemplate.courseId,
						rows.map((r) => r.course.id)
					)
				)
		: [];
	const out = [];
	for (const r of rows) {
		const [en] = await db
			.select({ n: sql<number>`count(*)`.mapWith(Number) })
			.from(courseEnrollment)
			.where(eq(courseEnrollment.courseId, r.course.id));
		const sessions = await courseSessions(orgId, r.course);
		const t = tpls.filter((x) => x.courseId === r.course.id).sort((a, b) => a.weekday - b.weekday);
		out.push({
			...r,
			enrolled: en?.n ?? 0,
			sessionsLeft: sessions.length,
			schedule: t.length
				? `${t.map((x) => WEEKDAYS_SHORT[x.weekday]).join('/')} ${t[0]!.startTime}`
				: null
		});
	}
	return out;
}

/**
 * Creates a course plus one bounded class template per weekday (`until: endsOn`,
 * `courseId` link) and materializes sessions immediately. The nightly template
 * run keeps generating sessions — and booking enrollees — until the course ends.
 */
export async function createCourse(ctx: OrgContext, input: v.InferOutput<typeof s.courseInput>) {
	if (input.endsOn < input.startsOn) error(400, 'End date must be on or after the start date');
	const [ct] = await db
		.select({ id: classType.id })
		.from(classType)
		.where(and(eq(classType.id, input.classTypeId), eq(classType.organizationId, ctx.orgId)));
	if (!ct) error(404, 'Class type not found');
	const [row] = await db
		.insert(course)
		.values({
			organizationId: ctx.orgId,
			name: input.name,
			description: input.description ?? '',
			classTypeId: input.classTypeId,
			startsOn: input.startsOn,
			endsOn: input.endsOn,
			priceCents: input.priceCents ?? 0,
			capacity: input.capacity ?? null,
			memberBookable: input.memberBookable ?? true,
			installments: input.installments ?? 1
		})
		.returning();
	await db.insert(classTemplate).values(
		[...new Set(input.weekdays)].map((weekday) => ({
			organizationId: ctx.orgId,
			classTypeId: input.classTypeId,
			locationId: input.locationId ?? null,
			instructorId: input.instructorId ?? null,
			weekday,
			startTime: input.startTime,
			until: input.endsOn,
			courseId: row!.id,
			active: true
		}))
	);
	const generated = await materializeTemplates(ctx.orgId);
	await emit({
		orgId: ctx.orgId,
		actorId: ctx.userId ?? null,
		entityType: 'course',
		entityId: row!.id,
		action: 'created',
		summary: `Course "${row!.name}" created${generated ? ` — ${generated} session${generated === 1 ? '' : 's'} scheduled` : ''}`
	});
	return row;
}

/** Removes a course only while it has no enrollees; deactivates its templates so sessions stop generating. */
export async function removeCourse(ctx: OrgContext, id: string) {
	const [row] = await db
		.select()
		.from(course)
		.where(and(eq(course.id, id), eq(course.organizationId, ctx.orgId)));
	if (!row) error(404, 'Course not found');
	const [en] = await db
		.select({ n: sql<number>`count(*)`.mapWith(Number) })
		.from(courseEnrollment)
		.where(eq(courseEnrollment.courseId, id));
	if ((en?.n ?? 0) > 0)
		error(
			409,
			`${en!.n} member${en!.n === 1 ? ' is' : 's are'} enrolled — cancel their enrollments first`
		);
	await db
		.update(classTemplate)
		.set({ active: false, updatedAt: new Date() })
		.where(eq(classTemplate.courseId, id));
	await db.delete(course).where(eq(course.id, id));
	await emit({
		orgId: ctx.orgId,
		actorId: ctx.userId ?? null,
		entityType: 'course',
		entityId: id,
		action: 'deleted',
		summary: `Course "${row.name}" removed`
	});
}

/** Who's enrolled in one course (staff roster). */
export async function courseRoster(orgId: string, courseId: string) {
	return db
		.select({
			enrollment: courseEnrollment,
			memberName: gymMember.name,
			memberEmail: gymMember.email
		})
		.from(courseEnrollment)
		.innerJoin(gymMember, eq(courseEnrollment.memberId, gymMember.id))
		.where(and(eq(courseEnrollment.organizationId, orgId), eq(courseEnrollment.courseId, courseId)))
		.orderBy(asc(courseEnrollment.createdAt));
}

/** Portal listing: open courses + the member's enrollments, with the weekly schedule. */
export async function portalCourses(orgId: string, memberId: string) {
	const rows = await db
		.select({ course, className: classType.name })
		.from(course)
		.innerJoin(classType, eq(course.classTypeId, classType.id))
		.where(
			and(
				eq(course.organizationId, orgId),
				eq(course.memberBookable, true),
				sql`${course.endsOn} >= ${todayISO()}`
			)
		)
		.orderBy(asc(course.startsOn));
	const tpls = rows.length
		? await db
				.select({
					courseId: classTemplate.courseId,
					weekday: classTemplate.weekday,
					startTime: classTemplate.startTime,
					locationName: location.name,
					instructorName: user.name
				})
				.from(classTemplate)
				.leftJoin(location, eq(classTemplate.locationId, location.id))
				.leftJoin(member, eq(classTemplate.instructorId, member.id))
				.leftJoin(user, eq(member.userId, user.id))
				.where(
					inArray(
						classTemplate.courseId,
						rows.map((r) => r.course.id)
					)
				)
		: [];
	const mine = await db
		.select({ courseId: courseEnrollment.courseId })
		.from(courseEnrollment)
		.where(eq(courseEnrollment.memberId, memberId));
	const enrolled = new Set(mine.map((m) => m.courseId));
	// The member's bookings on upcoming sessions of their enrolled courses —
	// cancelled rows included so a dropped occurrence can be re-booked.
	const myBookRows = mine.length
		? await db
				.select({
					bookingId: booking.id,
					courseId: classTemplate.courseId,
					status: booking.status,
					startsAt: classSession.startsAt
				})
				.from(booking)
				.innerJoin(classSession, eq(booking.sessionId, classSession.id))
				.innerJoin(classTemplate, eq(classSession.templateId, classTemplate.id))
				.where(
					and(
						eq(booking.memberId, memberId),
						gte(classSession.startsAt, new Date()),
						isNull(classSession.cancelledAt),
						inArray(
							classTemplate.courseId,
							mine.map((m) => m.courseId)
						)
					)
				)
				.orderBy(asc(classSession.startsAt))
		: [];
	const out = [];
	for (const r of rows) {
		const [en] = await db
			.select({ n: sql<number>`count(*)`.mapWith(Number) })
			.from(courseEnrollment)
			.where(eq(courseEnrollment.courseId, r.course.id));
		const n = en?.n ?? 0;
		const t = tpls.filter((x) => x.courseId === r.course.id).sort((a, b) => a.weekday - b.weekday);
		out.push({
			course: r.course,
			className: r.className,
			enrolled: n,
			full: r.course.capacity !== null && n >= r.course.capacity,
			mine: enrolled.has(r.course.id),
			schedule: t.length
				? `${t.map((x) => WEEKDAYS_SHORT[x.weekday]).join('/')} ${t[0]!.startTime}`
				: null,
			locationName: t[0]?.locationName ?? null,
			instructorName: t[0]?.instructorName ?? null,
			mySessions: enrolled.has(r.course.id)
				? myBookRows.filter((x) => x.courseId === r.course.id)
				: []
		});
	}
	return out;
}

/**
 * Enrolls a member: posts the signup charge (if priced), then books them into
 * every upcoming course session — 'waitlisted' when a session is full.
 * One enrollment per member per course (unique index enforced). Sessions
 * generated later (as the template horizon slides) book enrollees automatically
 * in materializeTemplates.
 */
export async function enrollCourse(orgId: string, memberId: string, courseId: string) {
	const [c] = await db
		.select()
		.from(course)
		.where(and(eq(course.id, courseId), eq(course.organizationId, orgId)));
	if (!c) error(404, 'Course not found');
	const [already] = await db
		.select({ id: courseEnrollment.id })
		.from(courseEnrollment)
		.where(and(eq(courseEnrollment.courseId, courseId), eq(courseEnrollment.memberId, memberId)));
	if (already) error(409, 'Already enrolled');
	if (c.capacity !== null) {
		const [en] = await db
			.select({ n: sql<number>`count(*)`.mapWith(Number) })
			.from(courseEnrollment)
			.where(eq(courseEnrollment.courseId, courseId));
		if ((en?.n ?? 0) >= c.capacity) error(409, 'Course is full');
	}
	const sessions = await courseSessions(orgId, c);
	if (!sessions.length) error(404, 'No upcoming sessions in this course');

	// Charge first so a failure doesn't leave bookings behind. Installments
	// split the price into equal monthly charges; the first is linked on the
	// enrollment, the rest are found by description prefix when voiding.
	let chargeRow = null;
	if (c.priceCents > 0) {
		const n = Math.min(12, Math.max(1, c.installments ?? 1));
		const per = Math.ceil(c.priceCents / n);
		for (let i = 0; i < n; i++) {
			const row = await addCharge(
				{ orgId },
				{
					memberId,
					kind: 'other',
					description:
						n > 1 ? `Course: ${c.name} — installment ${i + 1}/${n}` : `Course: ${c.name}`,
					amount: i === n - 1 ? c.priceCents - per * (n - 1) : per,
					dueDate: addDays(todayISO(), i * 30)
				}
			);
			chargeRow ??= row;
		}
	}
	const [enrollment] = await db
		.insert(courseEnrollment)
		.values({ organizationId: orgId, courseId, memberId, chargeId: chargeRow?.id ?? null })
		.returning();

	// Skip sessions the member is already booked into (unique open-booking index).
	const existing = await db
		.select({ sessionId: booking.sessionId })
		.from(booking)
		.where(
			and(
				eq(booking.memberId, memberId),
				ne(booking.status, 'cancelled'),
				inArray(
					booking.sessionId,
					sessions.map((x) => x.id)
				)
			)
		);
	const have = new Set(existing.map((e) => e.sessionId));
	const counts = await db
		.select({ sessionId: booking.sessionId, n: sql<number>`count(*)`.mapWith(Number) })
		.from(booking)
		.where(
			and(
				inArray(
					booking.sessionId,
					sessions.map((x) => x.id)
				),
				ne(booking.status, 'cancelled')
			)
		)
		.groupBy(booking.sessionId);
	const taken = new Map(counts.map((x) => [x.sessionId, x.n]));
	let booked = 0;
	let waitlisted = 0;
	for (const sess of sessions) {
		if (have.has(sess.id)) continue;
		const n = taken.get(sess.id) ?? 0;
		const status = n < sess.capacity ? 'booked' : 'waitlisted';
		await db.insert(booking).values({
			organizationId: orgId,
			sessionId: sess.id,
			memberId,
			status
		});
		taken.set(sess.id, n + 1);
		if (status === 'booked') booked++;
		else waitlisted++;
	}
	await emit({
		orgId,
		entityType: 'course',
		entityId: courseId,
		action: 'enrolled',
		summary: `Enrolled in course "${c.name}"${c.priceCents ? ` (${formatMoney(c.priceCents)})` : ''}`
	});
	return { enrollment, booked, waitlisted, charge: chargeRow };
}

/**
 * Member leaves a course: removes the enrollment, cancels their still-upcoming
 * bookings on course sessions, and voids the signup charge if it is unpaid.
 */
export async function unenrollCourse(orgId: string, memberId: string, courseId: string) {
	const [enrollment] = await db
		.select()
		.from(courseEnrollment)
		.where(
			and(
				eq(courseEnrollment.organizationId, orgId),
				eq(courseEnrollment.courseId, courseId),
				eq(courseEnrollment.memberId, memberId)
			)
		);
	if (!enrollment) error(404, 'Not enrolled');
	const [c] = await db.select().from(course).where(eq(course.id, courseId));
	const sessions = c ? await courseSessions(orgId, c) : [];
	if (sessions.length) {
		await db
			.update(booking)
			.set({ status: 'cancelled', cancelledAt: new Date() })
			.where(
				and(
					eq(booking.memberId, memberId),
					inArray(
						booking.sessionId,
						sessions.map((x) => x.id)
					),
					inArray(booking.status, ['booked', 'waitlisted'])
				)
			);
	}
	if (enrollment.chargeId) {
		// Void the whole installment series still open for this course.
		await db
			.update(charge)
			.set({ status: 'void', updatedAt: new Date() })
			.where(
				and(
					eq(charge.memberId, memberId),
					eq(charge.organizationId, orgId),
					eq(charge.status, 'open'),
					sql`${charge.description} like ${`Course: ${c?.name ?? ''}%`}`
				)
			);
	}
	await db.delete(courseEnrollment).where(eq(courseEnrollment.id, enrollment.id));
	await emit({
		orgId,
		entityType: 'course',
		entityId: courseId,
		action: 'unenrolled',
		summary: `Left course "${c?.name ?? courseId}"${enrollment.chargeId ? ' (charge voided if unpaid)' : ''}`
	});
	return { ok: true };
}

/** Cancel an enrollment by its own id (REST deletes address rows, not member+course). */
export async function cancelCourseEnrollment(orgId: string, enrollmentId: string) {
	const [enrollment] = await db
		.select({ memberId: courseEnrollment.memberId, courseId: courseEnrollment.courseId })
		.from(courseEnrollment)
		.where(and(eq(courseEnrollment.organizationId, orgId), eq(courseEnrollment.id, enrollmentId)));
	if (!enrollment) error(404, 'Enrollment not found');
	return unenrollCourse(orgId, enrollment.memberId, enrollment.courseId);
}

/**
 * Member re-books a course occurrence they previously dropped — the makeup
 * path. Verifies the booking is theirs, lives on a session generated by a
 * course template, is still upcoming, and that they're still enrolled; then
 * flips it back to booked (or waitlisted when the session filled since).
 */
export async function rebookCourseSession(orgId: string, memberId: string, bookingId: string) {
	const [row] = await db
		.select({
			booking,
			courseId: classTemplate.courseId,
			startsAt: classSession.startsAt,
			capacity: classSession.capacity,
			sessionCancelledAt: classSession.cancelledAt
		})
		.from(booking)
		.innerJoin(classSession, eq(booking.sessionId, classSession.id))
		.innerJoin(classTemplate, eq(classSession.templateId, classTemplate.id))
		.where(
			and(
				eq(booking.id, bookingId),
				eq(booking.organizationId, orgId),
				eq(booking.memberId, memberId)
			)
		);
	if (!row || !row.courseId) error(404, 'Course booking not found');
	if (row.booking.status !== 'cancelled') error(409, 'Booking is already active');
	if (row.sessionCancelledAt || row.startsAt.getTime() < Date.now())
		error(409, 'That session has already started');
	const [enr] = await db
		.select({ id: courseEnrollment.id })
		.from(courseEnrollment)
		.where(
			and(eq(courseEnrollment.courseId, row.courseId), eq(courseEnrollment.memberId, memberId))
		);
	if (!enr) error(409, 'Not enrolled in this course');
	// Same seat math as enrollCourse: non-cancelled bookings vs capacity.
	const [en] = await db
		.select({ n: sql<number>`count(*)`.mapWith(Number) })
		.from(booking)
		.where(and(eq(booking.sessionId, row.booking.sessionId), ne(booking.status, 'cancelled')));
	const status = (en?.n ?? 0) < row.capacity ? 'booked' : 'waitlisted';
	const [b] = await db
		.update(booking)
		.set({ status, cancelledAt: null })
		.where(and(eq(booking.id, bookingId), eq(booking.status, 'cancelled')))
		.returning();
	if (!b) error(409, 'Booking is already active');
	await emit({
		orgId,
		entityType: 'booking',
		entityId: bookingId,
		action: 'rebooked',
		summary: `Re-booked a course session (${status})`,
		data: { sessionId: row.booking.sessionId, memberId }
	});
	return b;
}
